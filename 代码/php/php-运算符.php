<?php

declare(strict_types=1);

// ============================================================
// 0. 准备：$_GET 在 CLI 模式下不存在，防止直接报错
// ============================================================
// 浏览器访问时 $_GET 由 PHP 自动填充（如 ?name=Tom）
// 命令行/单元测试时不存在，故用 ?? 兜底给个空数组
$_GET = $_GET ?? [];

// 注意：$_GET['name'] 可能不是字符串，而是数组（如 ?name[]=a）
// 因此真正过滤时还要判断 is_string，或者用 filter_input()
$raw  = $_GET['name'] ?? "匿名";       // 见下方"空合并"部分
$name = is_string($raw) ? $raw : "匿名";
// 生产环境还应做 HTML 转义：htmlspecialchars($name, ENT_QUOTES, 'UTF-8')

// ============================================================
// 1. 算术运算符：+  -  *  /  %  **
// ============================================================
$a = 7;
$b = 2;

echo $a + $b, PHP_EOL;       // 9    加
echo $a - $b, PHP_EOL;       // 5    减
echo $a * $b, PHP_EOL;       // 14   乘
echo $a / $b, PHP_EOL;       // 3.5  除：结果为 float（除非整除）
echo $a % $b, PHP_EOL;       // 1    取模：只对整数有效，符号跟被除数一致
                             //      -7 % 2 === -1
echo $a ** $b, PHP_EOL;      // 49   幂运算，等价于 pow($a, $b)，PHP 5.6+
// 注意：$a / 0 会抛 DivisionByZeroError（PHP 8+）；$a % 0 也报错
// 取余可用 fmod($a, $b) 处理浮点数

// ============================================================
// 2. 比较运算符：== === != <> !== < > <= >= <=>
// ============================================================
var_dump(1 == "1");          // true   松散比较：先转类型再比
var_dump(1 === "1");         // false  严格比较：类型也必须一致（推荐！）
var_dump(1 != "1");          // false  松散不等
var_dump(1 <> "1");          // false  <> 是 != 的别名，完全等价
var_dump(1 !== "1");         // true   严格不等

var_dump(3 < 5);             // true
var_dump(5 > 3);             // true
var_dump(5 <= 5);            // true

// 飞船运算符 <=>（PHP 7+）：返回 -1 / 0 / 1
// 常用于 usort / uasort 的回调
var_dump(1 <=> 2);           // -1   左 < 右
var_dump(2 <=> 2);           //  0   相等
var_dump(3 <=> 2);           //  1   左 > 右

// 坑：== 松散比较会让 "abc" == 0 在 PHP 7 中为 true，
//     PHP 8 已修正为 false，但跨版本代码仍建议一律用 ===
var_dump("abc" == 0);        // PHP7:true  PHP8:false

// ============================================================
// 3. 逻辑运算符：&& || !  and  or  xor
// ============================================================
// 关键区别：&& || ! 优先级高（高于赋值 =）；
//          and or xor 优先级低（低于赋值 =，仅高于 "," 和 "print"）
// 所以 "赋值 + and/or" 是合法写法，但极易误读，不推荐

$x = true;
$y = false;

var_dump($x && $y);          // false  AND，短路：$x 为 false 则不再看 $y
var_dump($x || $y);          // true   OR，短路：$x 为 true 则不再看 $y
var_dump(!$x);               // false  NOT
var_dump($x and $y);         // false  同 &&，但优先级低
var_dump($x or  $y);         // true   同 ||，但优先级低
var_dump($x xor $y);         // true   XOR：两个中恰好一个为真才为真

// 优先级陷阱演示（务必理解！）：
$result = true and false;    // 等价于 ($result = true) and false;
var_dump($result);           // true   ← 不是 false！

$result = true && false;     // 等价于 $result = (true && false);
var_dump($result);           // false  ← 正常结果

// 结论：日常都写 && || !，and/or/xor 只在特殊场景（如 $db or die()）用

// ============================================================
// 4. 字符串拼接：.  （点号）
// ============================================================
// PHP 里没有 "+"，拼接一律用 "."（这点与 JS/Python 不同）
$first = "Hello";
$last  = "World";
$full  = $first . " " . $last;
echo $full, PHP_EOL;         // Hello World

// .= 是拼接赋值（复合赋值）的简写
$msg = "Hi";
$msg .= ", Tom";
$msg .= "!";
echo $msg, PHP_EOL;          // Hi, Tom!

// 坑：数字 + 字符串会走"数值转换"而不是拼接
var_dump("1"+"2");         // int(3)  —— 这**不是**拼接
var_dump("1" . "2");         // string(2) "12"

// 拼接与三元/空合并结合时注意括号：
// $a . $b ?? 'x' 会先算 ??，实际是 $a . ($b ?? 'x')（PHP 8 起 ?? 优先级低于 .）

// ============================================================
// 5. 三元运算符：$a ? $b : $c   与   短三元 $a ?: $b
// ============================================================
$age = 20;

// 完整三元：条件为 true 取第 1 个，否则取第 2 个
echo $age >= 18 ? "成年" : "未成年", PHP_EOL;   // 成年

// 短三元 $a ?: $b：等价于 $a ? $a : $b
// 也就是"$a 为真值时用它本身，否则用 $b"
// 注意：判断的是"真假值"（falsy：0、""、"0"、null、false、[]）
$nickname = "";
echo $nickname ?: "匿名", PHP_EOL;              // 匿名（因为 "" 是 falsy）

// 坑：短三元在 ""、0 这类"合法但 falsy"的值下也会被替换
//     如果需要"仅在 null 时才替换"，用 ??，见下一节

// 嵌套三元（不推荐，可读性差）：
// $score = 85;
// $level = $score >= 90 ? "A" : ($score >= 60 ? "B" : "C");
// PHP 8 起必须加括号，否则报错（旧的左结合写法已废弃）

// ============================================================
// 6. 空合并运算符：$a ?? "默认"   （PHP 7+）
// ============================================================
// 语义：若 $a 存在且不为 null，返回 $a；否则返回右边。
// 与 ?: 的关键区别：
//   - ?? 只对 null 和"未定义"生效
//   - ?: 对"任何 falsy 值"生效（0、""、"0"、false、[] 都会触发）
// 因此"读可能不存在的键"应优先用 ??

echo $_GET['name'] ?? "匿名", PHP_EOL;           // 安全：键不存在不报 Warning
echo $name, PHP_EOL;                             // 上面处理过的 $name

// 对比演示
$arr = ["x" => 0];
var_dump($arr["x"] ?? "默认");   // int(0)     ← 0 不是 null，保留
var_dump($arr["x"] ?: "默认");   // "默认"      ← 0 是 falsy，被替换
var_dump($arr["y"] ?? "默认");   // "默认"      ← 键不存在

// ?? 支持链式：从左到右第一个非 null 的胜出
var_dump($a ?? $b ?? $c ?? "兜底"); // 若 $a/$b/$c 都未定义或为 null，得 "兜底"

// ??= （PHP 7.4+）：若左边为 null 或未定义，则赋值
$count = null;
$count ??= 100;
var_dump($count);                // int(100)

// ============================================================
// 7. 附：运算符优先级速览（从高到低，节选）
// ============================================================
//  **  →  !  →  * / %  →  + - .  →  < <= > >=  →  == != === !== <=>
//  →  &&  →  ||  →  ??  →  ?:  →  = += -= ...  →  and  →  xor  →  or
//
// 记忆口诀：
//   1) 算术 > 比较 > 逻辑 > 赋值 > and/or/xor
//   2) ?? 高于 ?: 高于赋值
//   3) 括号永远最稳，拿不准就加括号

?>