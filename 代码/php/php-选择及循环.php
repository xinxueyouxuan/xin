<?php
declare(strict_types=1);          // 开启严格类型（可选，但推荐）
error_reporting(E_ALL);           // 显示所有警告，方便调试

// ============================================================
// 0. 先初始化变量（原代码未定义，直接使用会报 Warning）
// ============================================================
$age   = 20;                       // 可以是任意整数，试改成 10、-1 看分支效果
$grade = "A";
$user  = ["name" => "Tom", "age" => 20];

// ============================================================
// 1. if / elseif / else
// ============================================================
// 条件自上而下依次判断；命中第一个 true 就执行，其余跳过
// 一旦有分支执行，整条 if 结构就结束（不会继续往下判断）
if ($age >= 18) {
    echo "成年";
} elseif ($age > 0) {              // 只有上面条件为 false 时才会到这里
    echo "未成年";
} else {                           // 以上都 false（如 age <= 0）
    echo "无效";
}
echo PHP_EOL;                      // 换行，避免与后续输出黏在一起

// ============================================================
// 2. switch
// ============================================================
// switch 表达式与各 case 用 == 松散比较（注意类型：1 == "1" 为 true）
// 每个 case 结尾必须 break，否则会"贯穿"到下一个 case
// default 建议也加 break（虽然它位于末尾时无副作用，但保持一致更安全）
switch ($grade) {
    case "A": echo "优秀"; break;
    case "B": echo "良好"; break;
    default:  echo "其他"; break;
}
echo PHP_EOL;

// ============================================================
// 3. for 循环
// ============================================================
// 语法：for (初始化 ; 条件 ; 步进)，适合"已知次数"的循环
// 注意：若条件一开始就为 false，循环体一次也不执行
for ($i = 0; $i < 5; $i++) {
    echo $i;                       // 输出 01234
}
echo PHP_EOL;

// ============================================================
// 4. foreach 遍历数组
// ============================================================
// foreach ($数组 as $键 => $值)：遍历关联数组最常用
// 只写 ($数组 as $值) 时，只拿值不拿键（索引数组常用）
// 注意：foreach 遍历的是数组的"副本"，循环体内修改 $val 不影响原数组；
//       若要修改原数组，需写成 foreach ($arr as $k => &$v)（引用）
foreach ($user as $key => $val) {
    echo "$key = $val";            // 双引号字符串内可直接插入变量
    echo PHP_EOL;                  // 每个键值对换行
}

// ============================================================
// 5. while 循环
// ============================================================
// 先判断后执行，条件一开始为 false 则一次都不执行
// 这里 $i 已在上面的 for 中被赋为 5，重新赋 0 起算
$i = 0;
while ($i < 3) {
    $i++;
}
echo $i, PHP_EOL;                  // 输出 3（循环退出时 $i 的终值）

// ============================================================
// 6. do-while 循环
// ============================================================
// 先执行一次再判断；即使条件为 false，循环体也至少执行 1 次
// 常用来"先处理一次，再决定要不要继续"
do {
    echo "至少执行一次";
} while (false);
echo PHP_EOL;

// ============================================================
// 7. break / continue 带层级
// ============================================================
// 语法：break N; / continue N;
//   - break N    : 跳出 N 层循环
//   - continue N : 跳过 N 层循环的当前迭代，直接进入第 N 层的下一次
// 数字省略时默认 1（等价于 break / continue）
for ($i = 0; $i < 3; $i++) {
    for ($j = 0; $j < 3; $j++) {
        if ($j === 1) continue 2;  // j=1 时：跳过内层剩余 + 跳过外层本次剩余
        if ($i === 2) break 2;     // i=2 时：直接跳出两层循环
        echo "$i-$j ";
    }
}
// 输出：0-0 1-0 2-0
echo PHP_EOL;
?>