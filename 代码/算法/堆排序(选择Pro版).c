#include <stdio.h>

// 辅助函数：交换两个变量的值
void swap(int *a, int *b) {
    int temp = *a;
    *a = *b;
    *b = temp;
}

/* 
 * 【核心动作：往下沉 (Heapify)】
 * 大白话：假设当前节点（i）是个小队长，突然换人了，新队长可能很菜，
 * 需要和自己的两个儿子（左孩子2i+1，右孩子2i+2）比一比，谁大谁当队长。
 * 如果儿子比爹大，就把儿子提上来，爹继续往下沉，直到沉到底或者比儿子都大。
 *
 * 参数说明：
 * arr[]: 存储堆的数组
 * n:     当前堆的有效元素个数（注意：在排序后期，排好序的尾部元素不再参与比较）
 * i:     当前需要进行“下沉”调整的节点索引
 */
void heapify(int arr[], int n, int i) {
    int max = i;        // 初始化最大值为当前父节点（假设老子最厉害）
    int left = 2*i + 1; // 计算左孩子的索引
    int right = 2*i + 2;// 计算右孩子的索引

    // 1. 先跟左儿子比：如果左孩子存在，且比当前最大值还大
    if(left < n && arr[left] > arr[max]){
        max = left;     // 记录新的最大值索引为左孩子
    }

    // 2. 再跟右儿子比：如果右孩子存在，且比当前最大值还大
    if(right < n && arr[right] > arr[max]){
        max = right;    // 记录新的最大值索引为右孩子
    }

    // 3. 如果最大值不是当前节点（说明儿子里有人比爹大）
    if(max != i){
        swap(&arr[i], &arr[max]); // 把最厉害的儿子提上来当爹，爹换到下面去
        heapify(arr, n, max);     // 【递归】：被换下去的原爹可能还是比下面的孙子小，需要继续往下沉
    }
}

// 堆排序主函数
void heapSort(int arr[], int n) {
    // 【第一步：建堆】
    // 前n/2个元素都是非叶子节点，依次从最后一个非叶子节点开始往前调整堆
    // 后面的都是叶子节点
    for(int i = n / 2 - 1; i >= 0; i--){
        heapify(arr, n, i);
    }

    // 此时，数组已经变成了一个“大顶堆”，arr[0] 绝对是整个数组里最大的数

    // 【第二步：排序】
    // 每次把堆顶（最大的数）换到数组末尾，然后重新调整剩下的元素
    for(int i = n - 1; i > 0; i--){
        swap(&arr[0], &arr[i]); 
        // 1. 将当前最大的堆顶 arr[0] 放到当前未排序部分的末尾 arr[i]
        
        // 2. 对剩下的 i 个元素（索引0到i-1）重新堆化。
        // 注意：这里传入的是 i，而不是 n。因为后面已经排好序的元素就不准再参与比较了。
        heapify(arr, i, 0);     
    }
}

/*
时间复杂度:无论数据是乱序还是全都有序;最好,最坏,平均都是O(nlogn)
空间复杂度:O(1);不需要额外申请新空间，就在原数组里换来换去。
稳定性:不稳定。
因为堆排序在交换元素时（比如把堆顶和最末尾的元素远距离交换），可能会改变相同元素的相对位置。
*/

int main() {

    int arr[10] = {18, 98, 12, 41, 53, 31, 65, 23, 76, 89};
    int n = 10;

    printf("原始数组: ");
    for(int i = 0; i < n; i++){
        printf("%d ", arr[i]);
    }
    printf("\n");
    
    // 调用堆排序函数，对数组 arr 进行原地排序
    heapSort(arr, n);

    printf("堆排序后数组: ");
    for(int i = 0; i < n; i++){
        printf("%d ", arr[i]);
    }
    printf("\n");

    return 0;
}