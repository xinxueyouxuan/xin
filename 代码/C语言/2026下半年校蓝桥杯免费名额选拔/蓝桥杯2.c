/*
题目描述 
社团成立十周年，准备办一场抽奖。每位到场的同学都会领到一张入场券，券上印着一个正整数编号。社长定的规则很特别：只有编号本身是质数的入场券才算中奖。

这里的质数指大于 1、且只能被 1 和自身整除的正整数。现在桌上摆着 n 张入场券，编号可能重复。请你统计有多少张券中奖，并算出这些中奖券的编号之和——后者要用来估算奖品预算。

输入描述:
第一行一个整数 n。
第二行 n 个正整数，依次为各张入场券的编号，相邻两数之间用一个空格分隔。
输出描述:
输出一行两个整数，用一个空格分隔，依次为中奖券的张数与中奖编号之和。若没有任何券中奖，输出 0 0。

示例1
输入
5
2 3 4 5 9
输出
3 10
备注:
1 ≤ n ≤ 2×10⁵，1 ≤ 编号 ≤ 10⁷。注意 1 不是质数。编号之和最大可达 2×10¹²，需要使用 64 位整数。
*/
#include<stdio.h>

int main(void){
    long n,number=0,sum=0;
    scanf("%ld",&n);
    for(long i=0;i<n;i++){
        long x;
        scanf("%ld",&x);
        if(x==2){
            number++;
            sum+=x;
        }
        else if(x>2 && x%2!=0){
            int flag=1;
            for(long j=3;j<x/2;j+=2){
                if(x%j==0){
                    flag=0;
                    break;
                }
            }
            if(flag){
                number++;
                sum+=x;
            }
        }
    }
    printf("%ld %ld",number,sum);
    return 0;
}