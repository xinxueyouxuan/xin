/*
题目描述 
学期末，教务系统开放了 n 门选修课。小蓝所在的班级需要从中挑出 m 门，作为下学期的课程组合。两门课只要编号不同就算不同，选课顺序无所谓，所以这其实是在数“从 n 门里挑 m 门”有多少种挑法。
由于 n 可能很大，方案数会是一个天文数字。为了便于统计报表展示，只需要输出方案数对 1 000 000 007 取模的结果。本题共有 q 组询问，每组给出一个 n 和一个 m。

输入描述:
第一行一个整数 q。
接下来 q 行，每行两个整数 n, m，用一个空格分隔，表示一组询问。

输出描述:
输出 q 行，每行一个整数，表示对应询问的方案数对 1 000 000 007 取模的结果。

示例1
输入
3
5 2
10 0
6 3
输出
10
1
20
说明
从 5 门里挑 2 门有 10 种挑法；从 10 门里挑 0 门只有 1 种（什么都不选）；从 6 门里挑 3 门有 20 种挑法。

备注:
1 ≤ q ≤ 10⁵，0 ≤ m ≤ n ≤ 10⁶。模数 1 000 000 007 是一个质数。
*/
#include <stdio.h>

int main() {
    long q, n, m;
    scanf("%ld", &q);
    for (long i = 0; i < q; i++) {
        scanf("%ld %ld", &n, &m);
    }

    return 0;
}