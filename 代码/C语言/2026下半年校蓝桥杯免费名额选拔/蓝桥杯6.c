/*
题目描述 
学校食堂的冷链车今天要去市里拉一批食材。车厢的额定载重为 W 千克，超载会被查扣，所以装车总重量必须控制在额定载重以内。
本次共有 n 箱食材等待装车，第 i 箱重 wᵢ 千克、采购价 vᵢ 元。每箱食材只有这一箱，只能整箱装或者不装，不能拆开分装。食堂经理想让这一趟拉回的食材总采购价尽可能高，请你帮他算一算最大能拉回多少元。
输入描述:
第一行两个整数 n, W，用一个空格分隔。
接下来 n 行，每行两个整数 wᵢ, vᵢ，分别表示第 i 箱食材的重量与采购价。
输出描述:
输出一行一个整数，表示在不超过额定载重的前提下能拉回的最大总采购价。

示例1
输入
3 10
5 10
4 40
6 30
输出
70
说明
装第 2 箱（4 千克、40 元）与第 3 箱（6 千克、30 元），总重 4 + 6 = 10 千克，恰好不超载，总价 40 + 30 = 70 元，是所有方案中最高的。

备注:
1 ≤ n ≤ 100，1 ≤ W ≤ 10⁵，1 ≤ wᵢ ≤ 10⁵，1 ≤ vᵢ ≤ 10⁹。所有食材的总采购价可达 10¹¹，需要使用 64 位整数。
*/
#include <stdio.h>

int main(void){
    //定义变量
    long n,w,max=0;
    scanf("%ld %ld",&n,&w);
    //定义重量和价钱数组
    long weight[n],price[n];
    //给数组赋值
    for(int i=0;i < n;i++)
        scanf("%ld %ld",&weight[i],&price[i]);
    
    //定义一个数组sum来存储每个重量下的最大总采购价
    long sum[w+1];
    //初始化sum数组为0
    for(int i=0;i <= w;i++)
        sum[i]=0;
    
//原理：对于每个物品，我们考虑是否将其放入背包中。
//如果放入，则价值为该物品的价值加上剩余容量下的最大价值；
//如果不放入，则价值保持不变。
    
    //动态规划求解最大总采购价
    for(int i=0;i < n;i++){
    //以weight[i]为背包容量，从后往前遍历重量
        for(int j=w;j >= weight[i];j--){
    //如果当前重量下的最大总采购价小于
    //当前箱子的价钱加上剩余重量下的最大总采购价
            if(price[i]+sum[j-weight[i]]>sum[j]){
    //更新sum[j]
                sum[j]=price[i]+sum[j-weight[i]];
                }
        }
    }
    //找出sum数组中的最大值，即为最大总采购价
    for(int i=0;i <= w;i++){
        if(sum[i]>max)
            max=sum[i];
    }
    
    printf("%ld",max);
    return 0;
}