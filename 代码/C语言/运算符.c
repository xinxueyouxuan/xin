#include <stdio.h>

// 结构体仅用于演示成员访问运算符
struct Point {
    int x;
    int y;
};

int main() {
    int a = 10, b = 3;
    int arr[3] = {5, 6, 7};

    // ---------- 1. 算术运算符 ----------
    printf("1. 算术: + %d, - %d, * %d, / %d, %% %d\n",
           a + b, a - b, a * b, a / b, a % b);
    int post_inc = a++;                     // 后缀 ++
    printf("   后缀 a++: 表达式值=%d, 之后 a=%d\n", post_inc, a);
    int pre_inc = ++a;                      // 前缀 ++
    printf("   前缀 ++a: 表达式值=%d, 现在 a=%d\n", pre_inc, a);

    // ---------- 2. 关系运算符 ----------
    printf("2. 关系: > %d, < %d, >= %d, <= %d, == %d, != %d\n",
           a > b, a < b, a >= b, a <= b, a == b, a != b);

    // ---------- 3. 逻辑运算符 ----------
    printf("3. 逻辑: && %d, || %d, ! %d\n",
           a > 0 && b > 0,    // 与（短路）
           a < 0 || b < 0,    // 或（短路）
           !(a == b));        // 非

    // ---------- 4. 位运算符 ----------
    a = 6;  b = 3;   // 二进制: 0110, 0011
    printf("4. 位: & %d, | %d, ^ %d, ~ %d, <<1 %d, >>1 %d\n",
           a & b, a | b, a ^ b, ~a, a << 1, a >> 1);

    // ---------- 5. 赋值运算符 ----------
    int c = 10;
    c += 5;   c *= 2;   c %= 7;   // 复合赋值
    printf("5. 赋值: 经过 +=,*=,%= 后 c=%d\n", c);

    // ---------- 6. 条件运算符（三目） ----------
    int max = (a > b) ? a : b;
    printf("6. 条件: (a>b)?a:b = %d\n", max);

    // ---------- 7. 逗号运算符 ----------
    int x, y;
    x = (y = 3, y + 2);   // 整个表达式的值为 y+2
    printf("7. 逗号: x=(y=3,y+2) -> x=%d, y=%d\n", x, y);

    // ---------- 8. 指针与地址运算符 ----------
    int *p = &a;          // & 取地址，* 解引用
    printf("8. 指针: &a=%p, *p=%d\n", (void*)&a, *p);

    // ---------- 9. 成员访问运算符（需结构体，此处开始单独使用结构体）----------
    {
        struct Point pt = {1, 2};      // 结构体变量
        struct Point *pp = &pt;        // 结构体指针
        printf("9. 成员访问: pt.x=%d, pt.y=%d   (. 访问)\n", pt.x, pt.y);
        printf("             pp->x=%d, pp->y=%d (-> 访问)\n", pp->x, pp->y);
    }
    // 离开代码块后 pt 和 pp 不再存在，后续不再使用结构体

    // ---------- 10. sizeof 运算符 ----------
    printf("10. sizeof: int=%zu, double=%zu\n",
           sizeof(int), sizeof(double));

    // ---------- 11. 强制类型转换 ----------
    double d = (double)a / b;    // 强制转换避免整除
    printf("11. 强制转换: (double)a / b = %f\n", d);

    // ---------- 12. 下标运算符 ----------
    arr[1] = 100;
    printf("12. 下标: arr[1]=%d\n", arr[1]);

    // ---------- 13. 函数调用运算符 () ----------
    // 上面所有 printf 都在使用 ()

    return 0;
}
